// Get all districts
export const getAllDistricts = () => {
  return Object.keys(MAHARASHTRA_DISTRICTS_TALUKAS).sort();
};

// Get talukas for a specific district
export const getTalukasForDistrict = (district) => {
  return MAHARASHTRA_DISTRICTS_TALUKAS[district] || [];
};

// Get all talukas across Maharashtra
export const getAllTalukas = () => {
  const allTalukas = [];
  Object.values(MAHARASHTRA_DISTRICTS_TALUKAS).forEach(talukas => {
    allTalukas.push(...talukas);
  });
  return allTalukas.sort();
};

